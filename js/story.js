// Сюжет игры. Каждая сцена — объект:
//   text:    массив строк или функция (state) => массив. Строки — текст рассказчика,
//            E('...') — реплика ЭХО, S('...') — системное сообщение.
//   choices: [{ t, to, if?, do?, cost?, puzzle? }]
//            if   — условие показа, do — эффект, cost — расход кислорода (по умолчанию 3).
//   onEnter: эффект при входе в сцену.
//   ending:  { id, title } — сцена-концовка.

export const E = (t) => ({ who: 'echo', t });
export const S = (t) => ({ who: 'sys', t });

const has = (s, item) => s.inv.includes(item);
const give = (s, item) => { if (!has(s, item)) s.inv.push(item); };
const back = (to, t = 'Вернуться') => ({ t, to, cost: 1 });

